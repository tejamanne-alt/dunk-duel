    /// <summary>
    /// Keeps Assets/DunkDuel/Sim/Core/SimBuildInfo.g.cs in sync with the sim sources (same format and hash as
    /// Tools/SimTool hash), on Editor load and before every player build. The hash is part of the sim version
    /// the netcode handshake compares, so mismatched builds refuse to play each other.
    /// </summary>
    [InitializeOnLoad]
    public static class SimCodeHash
    {
        public const string SimFolder = "Assets/DunkDuel/Sim";
        public const string GeneratedPath = "Assets/DunkDuel/Sim/Core/SimBuildInfo.g.cs";

        static SimCodeHash()
        {
            EditorApplication.delayCall += () => Refresh(false);
        }

        [MenuItem("DunkDuel/Sim/Regenerate Code Hash", false, 20)]
        public static void RegenerateFromMenu()
        {
            bool changed = Refresh(true);
            Debug.Log(changed ? "Dunk Duel: sim code hash regenerated." : "Dunk Duel: sim code hash already current.");
        }

        public static ulong Compute()
        {
            string root = Path.GetFullPath(SimFolder).Replace('\\', '/');
            if (!root.EndsWith("/")) root += "/";
            var files = new List<KeyValuePair<string, string>>();
            foreach (string full in Directory.GetFiles(SimFolder, "*.cs", SearchOption.AllDirectories))
            {
                string abs = Path.GetFullPath(full).Replace('\\', '/');
                string rel = abs.StartsWith(root) ? abs.Substring(root.Length) : abs;
                files.Add(new KeyValuePair<string, string>(rel, File.ReadAllText(full)));
            }
            return SimBuildInfo.ComputeCodeHash(files);
        }

        public static string Generated(ulong hash)
        {
            var sb = new StringBuilder();
            sb.Append("// <auto-generated>\n");
            sb.Append("// Regenerate with: dotnet run --project Tools/SimTool -- hash\n");
            sb.Append("// (The Unity Editor also refreshes it before every player build.)\n");
            sb.Append("// </auto-generated>\n");
            sb.Append("namespace DunkDuel.Sim\n{\n    public static partial class SimBuildInfo\n    {\n");
            sb.Append("        public const ulong CodeHash = 0x").Append(hash.ToString("X16")).Append("UL;\n");
            sb.Append("    }\n}\n");
            return sb.ToString();
        }

        /// <summary>Rewrites the generated file if stale. Returns true when it changed.</summary>
        public static bool Refresh(bool log)
        {
            if (!Directory.Exists(SimFolder)) return false;
            string want = Generated(Compute());
            string have = File.Exists(GeneratedPath) ? File.ReadAllText(GeneratedPath).Replace("\r", "") : "";
            if (have == want) return false;
            File.WriteAllText(GeneratedPath, want);
            AssetDatabase.ImportAsset(GeneratedPath);
            if (log) Debug.Log("Dunk Duel: SimBuildInfo.g.cs updated.");
            return true;
        }
    }

    public sealed class SimCodeHashBuildStep : IPreprocessBuildWithReport
    {
        public int callbackOrder => -100;

        public void OnPreprocessBuild(BuildReport report)
        {
            if (SimCodeHash.Refresh(true)) Debug.LogWarning("Dunk Duel: the sim code hash was stale and has been regenerated for this build.");
            GoldenReplayStaging.Stage();
        }
    }

    /// <summary>
    /// Copies the golden 10,000-frame replay and its hashes into Resources so the on-device determinism check
    /// (Developer menu) can compare iPhone and Android results with EditMode. Generated folder: do not edit.
    /// </summary>
    public static class GoldenReplayStaging
    {
        public const string Source = "Assets/DunkDuel/Tests/EditMode/Data";
        public const string Target = "Assets/DunkDuel/Data/Resources/DunkDuelDev";

        [MenuItem("DunkDuel/Dev/Stage Golden Replay", false, 40)]
        public static void Stage()
        {
            string replay = Source + "/golden_10000.ddreplay";
            string json = Source + "/golden_10000.json";
            if (!File.Exists(replay) || !File.Exists(json)) return;
            ProjectSetup.EnsureFolder(Target);
            CopyIfChanged(replay, Target + "/golden_10000.bytes");
            CopyIfChanged(json, Target + "/golden_10000_hash.json");
        }

        private static void CopyIfChanged(string from, string to)
        {
            byte[] src = File.ReadAllBytes(from);
            if (File.Exists(to))
            {
                byte[] dst = File.ReadAllBytes(to);
                if (dst.Length == src.Length)
                {
                    bool same = true;
                    for (int i = 0; i < src.Length && same; i++) same = src[i] == dst[i];
                    if (same) return;
                }
            }
            File.WriteAllBytes(to, src);
            AssetDatabase.ImportAsset(to);
        }
    }

    /// <summary>Validates every data table the way the game loads them; errors name the file and key.</summary>
    public static class DataValidation
    {
        [MenuItem("DunkDuel/Validate Data", false, 10)]
        public static void ValidateFromMenu()
        {
            string report = Validate(out bool ok);
            if (ok) Debug.Log(report);
            else Debug.LogError(report);
            EditorUtility.DisplayDialog("Dunk Duel data", report, "OK");
        }

        public static string Validate(out bool ok)
        {
            var sb = new StringBuilder();
            ok = true;
            try
            {
                var source = new FolderDataSource(Path.Combine(Application.dataPath, "DunkDuel", "Data", "Resources", "DunkDuelData"));
                SimTables tables = SimTables.Load(source);
                CpuTiers.Load(tables, source);
                sb.Append("Sim tables OK: ").Append(tables.FighterCount).Append(" fighters, data hash ").Append(tables.DataHash.ToString("X16")).Append('\n');
                sb.Append("Sim version ").Append(SimBuildInfo.Version(tables).ToString("X16")).Append('\n');
                for (int i = 0; i < tables.FighterCount; i++)
                {
                    FighterStats f = tables.Fighters[i];
                    sb.Append("  ").Append(f.Def.Id).Append(": height ").Append(f.Height.ToString(2)).Append(" reach ").Append(f.Reach.ToString(2))
                        .Append(" jump ").Append(f.JumpHeight.ToString(2)).Append(" dunks ").Append(f.CanDunk).Append('\n');
                }
            }
            catch (System.Exception e)
            {
                ok = false;
                sb.Append("Sim/AI data error: ").Append(e.Message).Append('\n');
            }
            try
            {
                PresentationData d = PresentationData.Load();
                sb.Append("Presentation OK: ").Append(d.Courts.Length).Append(" courts, ").Append(d.Camera.Recipes.Count).Append(" camera recipes, ")
                    .Append(d.Visuals.Length).Append(" fighter visuals\n");
                if (d.Courts.Length != 9)
                {
                    ok = false;
                    sb.Append("Expected nine courts.\n");
                }
            }
            catch (System.Exception e)
            {
                ok = false;
                sb.Append("Presentation data error: ").Append(e.Message).Append('\n');
            }
            return sb.ToString();
        }
    }

    /// <summary>Batch builds: Unity -batchmode -quit -projectPath . -executeMethod DunkDuel.Editor.BuildScripts.BuildAndroid</summary>
    public static class BuildScripts
    {
        [MenuItem("DunkDuel/Build/Android (APK)", false, 60)]
        public static void BuildAndroid()
        {
            EditorUserBuildSettings.buildAppBundle = false;
            Build(BuildTarget.Android, "Builds/Android/DunkDuel.apk");
        }

        [MenuItem("DunkDuel/Build/Android (App Bundle)", false, 61)]
        public static void BuildAndroidBundle()
        {
            EditorUserBuildSettings.buildAppBundle = true;
            Build(BuildTarget.Android, "Builds/Android/DunkDuel.aab");
        }

        [MenuItem("DunkDuel/Build/iOS (Xcode project)", false, 62)]
        public static void BuildIOS()
        {
            Build(BuildTarget.iOS, "Builds/iOS");
        }

        private static void Build(BuildTarget target, string path)
        {
            var scenes = new List<string>();
            foreach (EditorBuildSettingsScene s in EditorBuildSettings.scenes) if (s.enabled) scenes.Add(s.path);
            if (scenes.Count == 0) scenes.Add(ProjectSetup.BootScenePath);
            var options = new BuildPlayerOptions
            {
                scenes = scenes.ToArray(),
                locationPathName = path,
                target = target,
                targetGroup = BuildPipeline.GetBuildTargetGroup(target),
                options = BuildOptions.None,
            };
            BuildReport report = BuildPipeline.BuildPlayer(options);
            Debug.Log("Dunk Duel build " + target + ": " + report.summary.result + ", " + report.summary.totalSize / (1024 * 1024) + " MB, " + report.summary.totalTime);
            if (Application.isBatchMode && report.summary.result != BuildResult.Succeeded) EditorApplication.Exit(1);
        }
    }

#if UNITY_ANDROID
    /// <summary>Adds the VIBRATE permission the haptics plugin needs (Unity only adds it when Handheld.Vibrate is used).</summary>
    public sealed class HapticsManifestStep : UnityEditor.Android.IPostGenerateGradleAndroidProject
    {
        public int callbackOrder => 20;

        public void OnPostGenerateGradleAndroidProject(string path)
        {
            string manifest = Path.Combine(path, "src", "main", "AndroidManifest.xml");
            if (!File.Exists(manifest)) return;
            var doc = new System.Xml.XmlDocument();
            doc.Load(manifest);
            const string ns = "http://schemas.android.com/apk/res/android";
            System.Xml.XmlElement root = doc.DocumentElement;
            foreach (System.Xml.XmlNode n in root.SelectNodes("uses-permission"))
            {
                if (n is System.Xml.XmlElement e && e.GetAttribute("name", ns) == "android.permission.VIBRATE") return;
            }
            System.Xml.XmlElement perm = doc.CreateElement("uses-permission");
            perm.SetAttribute("name", ns, "android.permission.VIBRATE");
            root.PrependChild(perm);
            doc.Save(manifest);
        }
    }
#endif
