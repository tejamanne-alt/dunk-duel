using System;
using System.Collections.Generic;
using System.IO;
using System.Text;
using DunkDuel.AI;
using DunkDuel.Sim;
using DunkDuel.Sim.Data;
using DunkDuel.Sim.Session;

namespace DunkDuel.Tools
{
    public static class Program
    {
        public static int Main(string[] args)
        {
            string cmd = args.Length > 0 ? args[0] : "help";
            string repo = FindRepoRoot();
            try
            {
                switch (cmd)
                {
                    case "hash": return Hash(repo, args);
                    case "golden": return Golden(repo, args);
                    case "trace": return Trace(repo, args);
                    case "replay": return VerifyReplay(repo, args);
                    case "matchup": return Matchup.Run(LoadTables(repo), DataSource(repo), args);
                    default:
                        Console.WriteLine("usage: SimTool hash [--check] | golden [--check] | trace [p0 p1 tier seed] | replay <file>");
                        return cmd == "help" ? 0 : 2;
                }
            }
            catch (DataException e)
            {
                Console.Error.WriteLine("data error: " + e.Message);
                return 3;
            }
        }

        public static string FindRepoRoot()
        {
            string dir = AppContext.BaseDirectory;
            for (int i = 0; i < 12 && dir != null; i++)
            {
                if (Directory.Exists(Path.Combine(dir, "Assets", "DunkDuel", "Sim"))) return dir;
                dir = Path.GetDirectoryName(dir.TrimEnd(Path.DirectorySeparatorChar));
            }
            dir = Directory.GetCurrentDirectory();
            for (int i = 0; i < 12 && dir != null; i++)
            {
                if (Directory.Exists(Path.Combine(dir, "Assets", "DunkDuel", "Sim"))) return dir;
                dir = Path.GetDirectoryName(dir);
            }
            throw new InvalidOperationException("repo root not found");
        }

        public static IDataSource DataSource(string repo) =>
            new FolderDataSource(Path.Combine(repo, "Assets", "DunkDuel", "Data", "Resources", "DunkDuelData"));

        public static SimTables LoadTables(string repo) => SimTables.Load(DataSource(repo));

        // ------------------------------------------------------------------ hash

        public static ulong ComputeSimCodeHash(string repo)
        {
            string simDir = Path.Combine(repo, "Assets", "DunkDuel", "Sim");
            var files = new List<KeyValuePair<string, string>>();
            foreach (string path in Directory.GetFiles(simDir, "*.cs", SearchOption.AllDirectories))
            {
                string rel = Path.GetRelativePath(simDir, path).Replace('\\', '/');
                files.Add(new KeyValuePair<string, string>(rel, File.ReadAllText(path)));
            }
            return SimBuildInfo.ComputeCodeHash(files);
        }

        private static int Hash(string repo, string[] args)
        {
            ulong hash = ComputeSimCodeHash(repo);
            bool check = Array.IndexOf(args, "--check") >= 0;
            if (check)
            {
                if (hash != SimBuildInfo.CodeHash)
                {
                    Console.Error.WriteLine($"SimBuildInfo.g.cs is stale: generated 0x{SimBuildInfo.CodeHash:X16}, sources 0x{hash:X16}. Run: dotnet run --project Tools/SimTool -- hash");
                    return 1;
                }
                Console.WriteLine($"sim code hash OK 0x{hash:X16}");
                return 0;
            }
            string path = Path.Combine(repo, "Assets", "DunkDuel", "Sim", "Core", "SimBuildInfo.g.cs");
            var sb = new StringBuilder();
            sb.Append("// <auto-generated>\n");
            sb.Append("// Regenerate with: dotnet run --project Tools/SimTool -- hash\n");
            sb.Append("// (The Unity Editor also refreshes it before every player build.)\n");
            sb.Append("// </auto-generated>\n");
            sb.Append("namespace DunkDuel.Sim\n{\n    public static partial class SimBuildInfo\n    {\n");
            sb.Append($"        public const ulong CodeHash = 0x{hash:X16}UL;\n");
            sb.Append("    }\n}\n");
            File.WriteAllText(path, sb.ToString());
            Console.WriteLine($"wrote {path}: 0x{hash:X16}");
            return 0;
        }

        // ------------------------------------------------------------------ golden replay

        public const int GoldenTicks = 10000;

        public static string GoldenDir(string repo) => Path.Combine(repo, "Assets", "DunkDuel", "Tests", "EditMode", "Data");

        /// <summary>Deterministic CPU-vs-CPU match truncated to 10,000 ticks: the determinism gate's input.</summary>
        public static Replay RecordGoldenReplay(SimTables tables, IDataSource data)
        {
            var setup = MatchSetup.Versus(tables.FighterIndex("kofi"), tables.FighterIndex("juno"), 0xD0D0CAFEUL);
            var p0 = new CpuPlayer(tables, CpuTiers.Load(tables, data), CpuTier.Legend, 0, 1234);
            var p1 = new CpuPlayer(tables, CpuTiers.Load(tables, data), CpuTier.Pro, 1, 5678);
            var session = new LocalSession(tables, setup, p0, p1);
            for (int t = 0; t < GoldenTicks && !session.IsOver; t++) session.Tick();
            Replay replay = session.Recorder.Replay;
            replay.FinalHash = session.State.Hash();
            return replay;
        }

        private static int Golden(string repo, string[] args)
        {
            SimTables tables = LoadTables(repo);
            Replay replay = RecordGoldenReplay(tables, DataSource(repo));
            ReplayRunner.Result check = ReplayRunner.Run(tables, replay);
            if (check.FinalHash != replay.FinalHash)
            {
                Console.Error.WriteLine("nondeterminism: recorded and replayed hashes differ");
                return 1;
            }
            string dir = GoldenDir(repo);
            Directory.CreateDirectory(dir);
            File.WriteAllBytes(Path.Combine(dir, "golden_10000.ddreplay"), replay.ToBytes());
            string json = "{\n  \"simVersion\": \"" + SimBuildInfo.Version(tables).ToString("X16") + "\",\n  \"ticks\": " + replay.Ticks
                + ",\n  \"finalHash\": \"" + check.FinalHash.ToString("X16") + "\",\n  \"chainHash\": \"" + check.ChainHash.ToString("X16") + "\"\n}\n";
            File.WriteAllText(Path.Combine(dir, "golden_10000.json"), json);
            Console.WriteLine("golden replay: " + replay.Ticks + " ticks, final 0x" + check.FinalHash.ToString("X16") + ", chain 0x" + check.ChainHash.ToString("X16"));
            return 0;
        }

        private static int VerifyReplay(string repo, string[] args)
        {
            if (args.Length < 2) return 2;
            SimTables tables = LoadTables(repo);
            Replay r = Replay.FromBytes(File.ReadAllBytes(args[1]));
            ReplayRunner.Result res = ReplayRunner.Run(tables, r);
            Console.WriteLine($"ticks {res.Ticks}, final 0x{res.FinalHash:X16}, recorded 0x{r.FinalHash:X16}, sim version match: {r.SimVersion == SimBuildInfo.Version(tables)}");
            return res.FinalHash == r.FinalHash ? 0 : 1;
        }

        // ------------------------------------------------------------------ trace

        private static int Trace(string repo, string[] args)
        {
            SimTables tables = LoadTables(repo);
            string f0 = args.Length > 1 ? args[1] : "kofi";
            string f1 = args.Length > 2 ? args[2] : "meera";
            CpuTier tier = args.Length > 3 ? (CpuTier)Enum.Parse(typeof(CpuTier), args[3], true) : CpuTier.Legend;
            ulong seed = args.Length > 4 ? ulong.Parse(args[4]) : 42UL;
            var tiers = CpuTiers.Load(tables, DataSource(repo));
            var setup = MatchSetup.Versus(tables.FighterIndex(f0), tables.FighterIndex(f1), seed);
            var session = new LocalSession(tables, setup, new CpuPlayer(tables, tiers, tier, 0, seed * 3 + 1), new CpuPlayer(tables, tiers, tier, 1, seed * 7 + 2));
            var counts = new int[(int)SimEventType.Count];
            session.Ledger.Spawned += (e, age) =>
            {
                counts[(int)e.Type]++;
                switch (e.Type)
                {
                    case SimEventType.Jump:
                    case SimEventType.Land:
                    case SimEventType.Plant:
                    case SimEventType.Swipe:
                    case SimEventType.HypeBar:
                    case SimEventType.GatherStart:
                    case SimEventType.LooseBall:
                        return;
                }
                GameState st = session.State;
                string extra = "";
                if (e.Type == SimEventType.ShotRelease)
                {
                    FighterState d = st.Get(1 - e.Actor);
                    extra = $"  [{(ReleaseGrade)e.A} {(ShotZone)e.B} {st.Shot.Kind} P={st.Shot.MakeChance.ToString(2)} Q={st.Shot.Contest.ToString(2)} made={st.Shot.Made} def={d.Action}@{(d.X - e.X).ToString(2)}m y={d.Y.ToString(2)}]";
                }
                Console.WriteLine($"t{st.Tick,6} r{st.Round} {st.F0.Score}-{st.F1.Score} {e.Type,-18} p{e.Actor} a={e.A} b={e.B} x={e.X.ToString(2)}{extra}");
            };
            int guard = 0;
            while (!session.IsOver && guard++ < 60 * 60 * 15) session.Tick();
            GameState s = session.State;
            Console.WriteLine($"--- match over at tick {s.Tick} ({s.Tick / 60.0:F1}s): winner p{s.MatchWinner}, rounds {s.F0.RoundsWon}-{s.F1.RoundsWon}");
            for (int i = 0; i < 2; i++)
            {
                FighterState f = s.Get(i);
                Console.WriteLine($"p{i} {tables.Fighters[f.CharIndex].Def.Id}: FG {f.FgMade}/{f.FgAtt} deep {f.DeepMade}/{f.DeepAtt} dunks {f.Dunks} stl {f.Steals} blk {f.Blocks} chg {f.Charges} ankles {f.AnkleBreaks} posters {f.Posters} fin {f.Finishers}/{f.FinisherAtt} deny {f.Denials} TO {f.Turnovers} bites {f.BitesDrawn} hype {f.Hype}");
            }
            return 0;
        }
    }
}
